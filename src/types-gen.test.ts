import { describe, expect, test } from "bun:test";
import { parseConfig } from "./config";
import { exportedClasses, generateTypes, hashOf, isCurrent, LEGACY_TYPES_FILE, TYPES_FILE } from "./types-gen";

const config = (extra: string, date = "2026-11-18") => {
  const parsed = parseConfig(`{ "name": "demo", "main": "src/index.ts", "compatibility_date": "${date}", ${extra} }`);
  if (!parsed.ok) throw new Error(parsed.errors.join("; "));
  return parsed.value;
};

const ALL = `
  "vars": { "SITE": "demo" },
  "secrets": ["ADMIN_TOKEN"],
  "kv_namespaces": ["SESSIONS"],
  "d1_databases": ["DB"],
  "r2_buckets": ["UPLOADS"],
  "queues": ["EMAILS"],
  "analytics_engine_datasets": ["METRICS"],
  "durable_objects": { "VIEWS": "ViewCounter" },
  "services": [{ "binding": "PEER", "service": "other" }],
  "ratelimiters": [{ "binding": "LIMITER", "limit": 3, "period": 60 }],
  "assets": { "directory": "public", "binding": "ASSETS" },
  "version_metadata": "VERSION"
`;

describe("the file", () => {
  test("is Wrangler's file name, a script that declares Env and Cloudflare.Env", () => {
    expect(TYPES_FILE).toBe("worker-configuration.d.ts");
    const out = generateTypes(config(`"kv_namespaces": ["KV"]`));
    expect(out).toStartWith("/* eslint-disable */\n// Generated by Sproutboat by running `sproutboat types` (hash: ");
    expect(out).toContain('/// <reference types="sproutboat/types" />');
    expect(out).toContain("declare namespace Cloudflare {\n\tinterface Env extends __BaseEnv {}\n}");
    expect(out).toContain("interface Env extends __BaseEnv {}");
    // A script file, not a module: no import or export at the top level, so `Env` is global.
    expect(out).not.toMatch(/^(import|export) /m);
    // Past 2026-09-28 the handler gets env as a parameter, so nothing declares a global `env`.
    expect(out).not.toContain("declare const env");
  });

  test("a project before 2026-09-28 also gets the global env it must read", () => {
    expect(generateTypes(config(`"kv_namespaces": ["KV"]`, "2026-09-07"))).toContain("declare const env: Env;");
  });

  test("every binding kind reaches Env with its own type", () => {
    const out = generateTypes(config(ALL));
    for (const row of [
      'SITE: "demo";',
      "ADMIN_TOKEN: string; /* secret */",
      "SESSIONS: KVNamespaceAsync;",
      "DB: D1DatabaseAsync;",
      "UPLOADS: R2BucketAsync;",
      "EMAILS: Queue;",
      "METRICS: AnalyticsEngineDataset;",
      "VIEWS: DurableObjectNamespaceAsync; /* ViewCounter */",
      "PEER: FetcherAsync; /* service: other */",
      "LIMITER: RateLimit;",
      "ASSETS: FetcherAsync;",
      "VERSION: VersionMetadata;",
    ])
      expect(out).toContain(`\t${row}`);
  });

  test("bindings pinned with an id are read by binding name, not id", () => {
    const out = generateTypes(
      config(`"kv_namespaces": [{ "binding": "SESSIONS", "id": "kv_0123456789abcdef01234567" }]`),
    );
    expect(out).toContain("SESSIONS: KVNamespaceAsync;");
    expect(out).not.toContain("kv_0123456789abcdef01234567");
  });

  test("a project with no bindings still produces a valid Env", () => {
    const out = generateTypes(config(`"vars": {}`));
    expect(out).toContain("interface __BaseEnv {}");
    expect(out).toContain("interface Env extends __BaseEnv {}");
  });
});

describe("the options, as in wrangler types", () => {
  test("strict vars (the default) are literal types, and --strict-vars=false makes them string", () => {
    const c = config(`"vars": { "SITE": "demo" }`);
    expect(generateTypes(c)).toContain('SITE: "demo";');
    expect(generateTypes(c, { strictVars: false })).toContain("SITE: string;");
  });

  test("--env-interface renames the interface and its base", () => {
    const out = generateTypes(config(`"kv_namespaces": ["KV"]`), { envInterface: "MyEnv" });
    expect(out).toContain("interface MyEnv extends __BaseMyEnv {}");
    expect(out).toContain("interface Env extends __BaseMyEnv {}");
    expect(() => generateTypes(config(""), { envInterface: "not valid" })).toThrow("not a valid interface name");
  });

  test("--include-runtime=false drops the reference, --include-env=false drops Env", () => {
    const c = config(`"kv_namespaces": ["KV"]`);
    const noRuntime = generateTypes(c, { includeRuntime: false });
    expect(noRuntime).not.toContain("reference types");
    expect(noRuntime).toContain("KV: KVNamespaceAsync;");
    const noEnv = generateTypes(c, { includeEnv: false });
    expect(noEnv).toContain('/// <reference types="sproutboat/types" />');
    expect(noEnv).not.toContain("KV:");
  });

  test("the command line is recorded in the header", () => {
    expect(generateTypes(config(""), { command: "sproutboat types out.d.ts --strict-vars=false" })).toContain(
      "by running `sproutboat types out.d.ts --strict-vars=false` (hash:",
    );
  });
});

describe("Durable Objects", () => {
  const mainModule = { importPath: "./src/index", classes: ["ViewCounter"] };

  test("a binding whose class the TypeScript entry exports is typed with it, so stub methods are checked", () => {
    expect(generateTypes(config(`"durable_objects": { "VIEWS": "ViewCounter" }`), { mainModule })).toContain(
      '\tVIEWS: DurableObjectNamespaceAsync<import("./src/index").ViewCounter>;',
    );
  });

  test("a class the entry does not export stays untyped", () => {
    expect(generateTypes(config(`"durable_objects": { "ROOM": "ChatRoom" }`), { mainModule })).toContain(
      "ROOM: DurableObjectNamespaceAsync; /* ChatRoom */",
    );
  });

  test("before 2026-10-28 the synchronous namespace type is used", () => {
    expect(
      generateTypes(config(`"durable_objects": { "VIEWS": "ViewCounter" }`, "2026-10-27"), { mainModule }),
    ).toContain("VIEWS: DurableObjectNamespace; /* ViewCounter */");
  });

  test("exportedClasses finds exported classes, abstract ones too, and ignores the rest", () => {
    expect(
      exportedClasses(
        "export class A {}\nexport abstract class B {}\nclass C {}\n  export class D extends X {}\n// export class E {}\n",
      ),
    ).toEqual(["A", "B", "D"]);
  });
});

describe("compatibility dates choose the Promise types", () => {
  const at = (date: string) =>
    generateTypes(
      config(
        `"d1_databases": ["DB"], "kv_namespaces": ["KV"], "r2_buckets": ["BUCKET"], "durable_objects": { "DO": "C" }, "services": [{ "binding": "SVC", "service": "x" }]`,
        date,
      ),
    );

  test("each binding switches on its own date", () => {
    const before = at("2026-10-21");
    for (const row of [
      "DB: D1Database;",
      "KV: KVNamespace;",
      "BUCKET: R2Bucket;",
      "DO: DurableObjectNamespace;",
      "SVC: Fetcher;",
    ])
      expect(before).toContain(row);
    expect(at("2026-10-22")).toContain("SVC: FetcherAsync;");
    expect(at("2026-10-24")).toContain("DB: D1DatabaseAsync;");
    expect(at("2026-10-24")).toContain("KV: KVNamespace;");
    expect(at("2026-10-25")).toContain("KV: KVNamespaceAsync;");
    expect(at("2026-10-25")).toContain("BUCKET: R2Bucket;");
    expect(at("2026-10-26")).toContain("BUCKET: R2BucketAsync;");
    expect(at("2026-10-27")).toContain("DO: DurableObjectNamespace;");
    expect(at("2026-10-28")).toContain("DO: DurableObjectNamespaceAsync;");
  });
});

describe("the hash", () => {
  const first = generateTypes(config(`"kv_namespaces": ["KV"]`));

  test("is read back from the header", () => {
    expect(hashOf(first)).toMatch(/^[0-9a-f]{32}$/);
    expect(hashOf("// hand written")).toBeUndefined();
  });

  test("is the same for the same input, whatever command line is recorded", () => {
    const again = generateTypes(config(`"kv_namespaces": ["KV"]`), { command: "sproutboat types other.d.ts" });
    expect(isCurrent(first, again)).toBe(true);
  });

  test("changes with a binding, a flag or the date, and ignores a hand edit outside the body's first line", () => {
    expect(isCurrent(first, generateTypes(config(`"kv_namespaces": ["KV", "MORE"]`)))).toBe(false);
    expect(
      isCurrent(first, generateTypes(config(`"kv_namespaces": ["KV"]`), { strictVars: false, envInterface: "E" })),
    ).toBe(false);
    expect(isCurrent(first, generateTypes(config(`"kv_namespaces": ["KV"]`, "2026-10-01")))).toBe(false);
    expect(isCurrent("// not generated", first)).toBe(false);
  });

  test("the file earlier releases wrote has another name", () => {
    expect(LEGACY_TYPES_FILE).toBe("sproutboat-env.d.ts");
  });
});
