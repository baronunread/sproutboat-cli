/**
 * The CLI describes itself. This test renders the command / env / toolchain
 * surface to `SURFACE.md` at the repo root and fails if the committed file is
 * stale — regenerate with `UPDATE_SURFACE=1 bun test`.
 *
 * It also cross-checks the source so the doc can't quietly drift:
 *   - every `case "x":` in main.ts's command switch is in COMMANDS, and vice versa
 *   - every SPROUTBOAT_* / PORFFOR_VERSION / XDG_CONFIG_HOME env read in src/
 *     (outside tests) is documented in ENV_VARS
 */
import { describe, expect, test } from "bun:test";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  CLI_NAME,
  COMMANDS,
  ENV_VARS,
  GLOBAL_FLAGS,
  STORAGE_PRODUCTS,
  STORAGE_VERBS,
  helpText,
  usageLine,
} from "./surface";
import { ARTIFACT_SCHEMA_VERSION, CAPABILITY_PROFILE, RUNTIME } from "./manifest";
import { ZIG_VERSION, toolchainStamp } from "./toolchain";
import { CLI_VERSION as version } from "./report";

const srcDir = import.meta.dir;
const root = resolve(srcDir, "..");

function render(): string {
  const rows = (cells: string[][]) => cells.map((r) => `| ${r.join(" | ")} |`).join("\n");
  return [
    `# ${CLI_NAME} — surface`,
    "",
    "> Generated by `src/surface.test.ts` from `src/surface.ts` + the pinned",
    "> toolchain constants. Do not edit by hand — run `UPDATE_SURFACE=1 bun test`.",
    "",
    `**Package:** \`sproutboat\` ${version}`,
    "",
    "## Commands",
    "",
    "| Command | Arguments | Summary |",
    "| --- | --- | --- |",
    rows(COMMANDS.map((c) => [`\`${c.name}\``, c.args ? `\`${c.args}\`` : "—", c.summary])),
    "",
    "```",
    usageLine(),
    "```",
    "",
    "## Global flags",
    "",
    "| Flag | Purpose |",
    "| --- | --- |",
    rows(GLOBAL_FLAGS.map((f) => [`\`${f.flags}\``, f.purpose])),
    "",
    "## Environment variables",
    "",
    "| Variable | Purpose |",
    "| --- | --- |",
    rows(ENV_VARS.map((e) => [`\`${e.name}\``, e.purpose])),
    "",
    "## Build toolchain (pinned)",
    "",
    "| | |",
    "| --- | --- |",
    rows([
      ["Zig", `\`${ZIG_VERSION}\` (\`zig cc -target x86_64-linux-musl\`, static)`],
      ["Provenance stamp", `\`${toolchainStamp()}\``],
      ["Artifact schema", `\`${ARTIFACT_SCHEMA_VERSION}\``],
      ["Runtime", `\`${RUNTIME}\``],
      ["Capability profile", `\`${CAPABILITY_PROFILE}\``],
    ]),
    "",
  ].join("\n");
}

const surfacePath = resolve(root, "SURFACE.md");

test("SURFACE.md is up to date", () => {
  const rendered = render();
  if (process.env.UPDATE_SURFACE === "1") {
    writeFileSync(surfacePath, rendered);
    return;
  }
  let onDisk = "";
  try {
    onDisk = readFileSync(surfacePath, "utf8");
  } catch {
    /* missing -> fail below */
  }
  expect(onDisk, "SURFACE.md is stale or missing — run `UPDATE_SURFACE=1 bun test`").toBe(rendered);
});

test("the command switch and COMMANDS agree", () => {
  const main = readFileSync(resolve(srcDir, "main.ts"), "utf8");
  const switched = new Set([...main.matchAll(/case "([a-z0-9-]+)":/g)].map((m) => m[1]));
  const documented = new Set(COMMANDS.map((c) => c.name));
  expect([...switched].sort()).toEqual([...documented].sort());
});

test("every env var read in src/ is documented in ENV_VARS", () => {
  const documented = new Set(ENV_VARS.map((e) => e.name));
  const seen = new Set<string>();
  for (const file of readdirSync(srcDir)) {
    // The embedded starters are other people's project code (their tests read BASE_URL), not the CLI's.
    if (!file.endsWith(".ts") || file.endsWith(".test.ts") || file === "templates-embedded.ts") continue;
    const text = readFileSync(resolve(srcDir, file), "utf8");
    for (const m of text.matchAll(/process\.env\.([A-Z][A-Z0-9_]*)/g)) {
      const name = m[1];
      // internal/plumbing + ambient vars that aren't part of the user-facing contract
      if (["PATH", "HOME", "CI", "DISPLAY", "WAYLAND_DISPLAY", "SSH_CONNECTION"].includes(name)) continue;
      seen.add(name);
    }
  }
  const undocumented = [...seen].filter((name) => !documented.has(name));
  expect(undocumented, `undocumented env vars: ${undocumented.join(", ")}`).toEqual([]);
});

test("no COMMANDS entry documents an env var that src/ never reads", () => {
  const referenced = new Set<string>();
  for (const file of readdirSync(srcDir)) {
    if (!file.endsWith(".ts") || file.endsWith(".test.ts")) continue;
    const text = readFileSync(resolve(srcDir, file), "utf8");
    // Two characters, not four: CC and AR are real env vars and the old bound
    // could never see them. Loose on purpose — some documented vars are set for
    // a child process rather than read here (SB_EXTRA_LINK), so this only asks
    // that the name appears in src/ at all.
    for (const m of text.matchAll(/([A-Z][A-Z0-9_]+)/g)) referenced.add(m[1]);
  }
  const stale = ENV_VARS.map((e) => e.name).filter((name) => !referenced.has(name));
  expect(stale, `ENV_VARS lists names not found anywhere in src/: ${stale.join(", ")}`).toEqual([]);
});

/**
 * #79 — the storage products are the CLI's one place where four commands must
 * stay identical. These guard the promise the help text makes.
 */
test("every storage product is a command with the same verbs", () => {
  const documented = new Set(COMMANDS.filter((c) => c.group === "Storage").map((c) => c.name));
  expect([...documented].sort()).toEqual(STORAGE_PRODUCTS.map((p) => p.name).sort());

  for (const command of COMMANDS.filter((c) => c.group === "Storage")) {
    for (const verb of STORAGE_VERBS) expect(command.args, `${command.name} must offer ${verb}`).toContain(verb);
  }
});

test("main.ts dispatches every storage product to the shared handler", () => {
  const main = readFileSync(resolve(srcDir, "main.ts"), "utf8");
  for (const product of STORAGE_PRODUCTS) {
    expect(main, `no dispatch case for ${product.name}`).toContain(`case "${product.name}":`);
  }
});

/** The grouped help is what people read first: keep it short, plain and aligned. */
describe("the top-level help", () => {
  // Colour is off whenever stdout is not a TTY, as it is under the test runner.
  const plain = helpText();

  test("every command has one short line", () => {
    for (const command of COMMANDS) {
      expect(command.short.length, `${command.name}: ${command.short}`).toBeLessThanOrEqual(60);
      expect(command.short).not.toMatch(/[.\n]$/);
    }
  });

  test("every command appears once, under its group", () => {
    for (const command of COMMANDS) expect(plain, command.name).toMatch(new RegExp(`^  ${command.name}( |$)`, "m"));
    expect(plain.indexOf("SHIP")).toBeLessThan(plain.indexOf("  delete"));
    expect(plain.indexOf("  delete")).toBeLessThan(plain.indexOf("STORAGE"));
    expect(COMMANDS.find((c) => c.name === "delete")?.group).toBe("Ship");
  });

  test("emojis are unique and render two cells wide", () => {
    const emojis = COMMANDS.map((c) => c.emoji);
    expect(new Set(emojis).size, "two commands share an emoji").toBe(emojis.length);
    for (const emoji of emojis) {
      expect(Bun.stringWidth(emoji), `width of ${emoji}`).toBe(2);
      // Text-presentation symbols (⏮ ⌨ 🗄) need U+FE0F, or terminals draw them one cell wide.
      expect(/^\p{Emoji_Presentation}$/u.test(emoji) || emoji.endsWith("\uFE0F"), `${emoji} needs U+FE0F`).toBe(true);
    }
  });

  test("no internal jargon, and nothing that only fits one deployment", () => {
    const text = [plain, ...COMMANDS.map((c) => c.summary)].join("\n").replace(/--sprout\b/g, "");
    for (const jargon of [/native-fetch/, /\bbroker\b/, /id-less/, /\bsprout\b(?!\.generated)/, /your own VPS/])
      expect(text, String(jargon)).not.toMatch(jargon);
  });

  test("lists the global flags and points to per-command help", () => {
    expect(plain).toContain("GLOBAL FLAGS");
    for (const flag of GLOBAL_FLAGS) expect(plain).toContain(flag.flags);
    expect(plain).toContain("Run `sproutboat <command> --help` for a command's options");
  });

  test("storage lines say what exists", () => {
    const kv = COMMANDS.find((c) => c.name === "kv")!;
    for (const word of ["keys", "bulk", "exports"]) expect(kv.short).toContain(word);
  });
});
