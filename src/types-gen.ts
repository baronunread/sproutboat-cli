/**
 * `sproutboat types` — the project's `Env`, as TypeScript, the way `wrangler types` writes it.
 *
 * The output is `worker-configuration.d.ts` (Wrangler's file name), a script file that declares an `Env` interface
 * and `Cloudflare.Env` (what `import { env } from "cloudflare:workers"` reads) from `sproutboat.jsonc`, then
 * references the ambient types shipped in `types/sproutboat.d.ts`. Binding *names* version with the project and
 * binding *shapes* with the CLI. A handler is typed with `satisfies ExportedHandler<Env>`.
 *
 * Names need no quoting: `parseConfig` already holds every binding and var to /^[A-Z][A-Z0-9_]*$/, so all of them
 * are plain identifiers.
 */
import { createHash } from "node:crypto";
import { resourceRefs, type SproutboatConfig } from "./config";

/** The file `sproutboat types` writes by default, relative to the project directory. */
export const TYPES_FILE = "worker-configuration.d.ts";

/** The file earlier releases wrote. It is only ever removed when it still carries its generated header. */
export const LEGACY_TYPES_FILE = "sproutboat-env.d.ts";
export const LEGACY_TYPES_HEADER = "// Generated by `sproutboat types`. Do not edit.";

export type TypesOptions = {
  /** Name of the interface (`--env-interface`). Default `Env`. */
  envInterface?: string;
  /** Literal types for `vars` (`--strict-vars`, default on); off, every var is a `string`. */
  strictVars?: boolean;
  /** Reference the runtime types shipped with the CLI (`--include-runtime`, default on). */
  includeRuntime?: boolean;
  /** Write the `Env` types (`--include-env`, default on). */
  includeEnv?: boolean;
  /** The command as typed, for the header. */
  command?: string;
  /**
   * The entry module, so a Durable Object binding is typed with its class and `stub.method()` is checked.
   * `importPath` is relative to the output file and has no extension; only a TypeScript entry is offered.
   */
  mainModule?: { importPath: string; classes: readonly string[] };
};

type Entry = { name: string; type: string; note?: string };

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** Whether a binding's calls return Promises at the project's compatibility date. */
function asyncAt(config: SproutboatConfig, date: string): boolean {
  return config.compatibility_date >= date;
}

/** `export class Name` declarations of an entry module, for typing Durable Object bindings. */
export function exportedClasses(source: string): string[] {
  return [...source.matchAll(/^\s*export\s+(?:abstract\s+)?class\s+([A-Za-z_$][A-Za-z0-9_$]*)/gm)].map(
    (match) => match[1]!,
  );
}

function entries(config: SproutboatConfig, options: TypesOptions): Entry[] {
  const out: Entry[] = [];
  const strictVars = options.strictVars ?? true;

  for (const [name, value] of Object.entries(config.vars ?? {})) {
    out.push({ name, type: strictVars ? JSON.stringify(value) : "string" });
  }
  for (const name of config.secrets ?? []) out.push({ name, type: "string", note: "secret" });
  for (const { binding } of resourceRefs(config.kv_namespaces))
    out.push({ name: binding, type: asyncAt(config, "2026-10-25") ? "KVNamespaceAsync" : "KVNamespace" });
  for (const { binding } of resourceRefs(config.d1_databases))
    out.push({ name: binding, type: asyncAt(config, "2026-10-24") ? "D1DatabaseAsync" : "D1Database" });
  for (const { binding } of resourceRefs(config.r2_buckets))
    out.push({ name: binding, type: asyncAt(config, "2026-10-26") ? "R2BucketAsync" : "R2Bucket" });
  for (const { binding } of resourceRefs(config.queues)) out.push({ name: binding, type: "Queue" });
  for (const name of config.analytics_engine_datasets ?? []) out.push({ name, type: "AnalyticsEngineDataset" });
  for (const [binding, className] of Object.entries(config.durable_objects ?? {})) {
    if (!asyncAt(config, "2026-10-28")) {
      out.push({ name: binding, type: "DurableObjectNamespace", note: className });
      continue;
    }
    const typed = options.mainModule?.classes.includes(className) && IDENTIFIER.test(className);
    out.push({
      name: binding,
      type: typed
        ? `DurableObjectNamespaceAsync<import(${JSON.stringify(options.mainModule!.importPath)}).${className}>`
        : "DurableObjectNamespaceAsync",
      note: typed ? undefined : className,
    });
  }
  for (const service of config.services ?? []) {
    out.push({
      name: service.binding,
      type: asyncAt(config, "2026-10-22") ? "FetcherAsync" : "Fetcher",
      note: `service: ${service.service}`,
    });
  }
  for (const limiter of config.ratelimiters ?? []) out.push({ name: limiter.binding, type: "RateLimit" });
  if (config.assets?.binding) {
    out.push({ name: config.assets.binding, type: asyncAt(config, "2026-10-22") ? "FetcherAsync" : "Fetcher" });
  }
  if (config.version_metadata) out.push({ name: config.version_metadata, type: "VersionMetadata" });
  return out;
}

const sha = (text: string) => createHash("sha256").update(text).digest("hex").slice(0, 32);

/** The hash a generated file carries in its first line, or `undefined` for anything else. */
export function hashOf(file: string): string | undefined {
  return /^\/\* eslint-disable \*\/\n\/\/ Generated by Sproutboat by running `[^\n]*` \(hash: ([0-9a-f]{32})\)\n/.exec(
    file,
  )?.[1];
}

/**
 * The contents of `worker-configuration.d.ts` for `config`.
 *
 * Pure, so the tests can assert on the text and `dev` can compare it with what is on disk without writing.
 */
export function generateTypes(config: SproutboatConfig, options: TypesOptions = {}): string {
  const name = options.envInterface ?? "Env";
  if (!IDENTIFIER.test(name)) throw new Error(`"${name}" is not a valid interface name`);
  const includeRuntime = options.includeRuntime ?? true;
  const includeEnv = options.includeEnv ?? true;
  const legacy = config.compatibility_date < "2026-09-28";

  const parts: string[] = [];
  if (includeRuntime) parts.push('/// <reference types="sproutboat/types" />');
  if (includeEnv) {
    const rows = entries(config, options);
    const base = `__Base${name}`;
    const members = rows.map((row) => `\t${row.name}: ${row.type};${row.note ? ` /* ${row.note} */` : ""}`);
    parts.push(
      `interface ${base} {${members.length ? `\n${members.join("\n")}\n` : ""}}`,
      `declare namespace Cloudflare {\n\tinterface Env extends ${base} {}\n}`,
      `interface ${name} extends ${base} {}`,
    );
    // Before compatibility date 2026-09-28 the handler is `fetch(request, ctx)` and `env` is only a global.
    if (legacy) parts.push(`declare const env: ${name};`);
  }
  const body = parts.join("\n") + "\n";
  const command = options.command ?? "sproutboat types";
  return `/* eslint-disable */\n// Generated by Sproutboat by running \`${command}\` (hash: ${sha(body)})\n${body}`;
}

/** Whether `file` is what `generateTypes` would write for the same input, by the hash in its header. */
export function isCurrent(file: string, wanted: string): boolean {
  const have = hashOf(file);
  return have !== undefined && have === hashOf(wanted);
}
