/**
 * Embed the starter templates in the CLI.
 *
 * `templates/<name>/` are real projects: CI runs each one (typecheck, tests, standalone, workerd). `sproutboat init
 * --template <name>` has to find them in the compiled executable, which carries no files of its own, so this writes
 * every text file of every template into `src/templates-embedded.ts`, a module the executable bundles like any other.
 *
 *   bun scripts/embed-templates.ts           # rewrite src/templates-embedded.ts
 *   bun scripts/embed-templates.ts --check   # exit 1 when it is out of date (src/templates.test.ts runs this check)
 *
 * What is left out, because a project generates or installs it: worker-configuration.d.ts (`init` runs
 * `sproutboat types` on the new project, so its hash matches the project's name), node_modules, build output,
 * lockfiles and `.dev.vars`.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { isString, jsonObject, parseJsonValue } from "../src/json";

const ROOT = resolve(import.meta.dir, "..");
const TEMPLATES = join(ROOT, "templates");
const OUTPUT = join(ROOT, "src/templates-embedded.ts");

const SKIPPED_NAMES = new Set([
  "worker-configuration.d.ts",
  "node_modules",
  ".sproutboat",
  "dist",
  ".dev.vars",
  "package-lock.json",
  "bun.lock",
  "pnpm-lock.yaml",
  "yarn.lock",
  ".DS_Store",
]);

export interface EmbeddedTemplate {
  description: string;
  files: Map<string, string>;
}

function filesOf(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => !SKIPPED_NAMES.has(entry.name))
    .flatMap((entry) => (entry.isDirectory() ? filesOf(join(dir, entry.name)) : [join(dir, entry.name)]))
    .sort();
}

export function readTemplates(): Map<string, EmbeddedTemplate> {
  const found = new Map<string, EmbeddedTemplate>();
  if (!existsSync(TEMPLATES)) return found;
  for (const entry of readdirSync(TEMPLATES, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory() || entry.name.startsWith(".") || SKIPPED_NAMES.has(entry.name)) continue;
    const dir = join(TEMPLATES, entry.name);
    const files = new Map<string, string>();
    for (const file of filesOf(dir)) files.set(relative(dir, file).split("\\").join("/"), readFileSync(file, "utf8"));
    const description = jsonObject(parseJsonValue(files.get("package.json") ?? "{}"))?.description;
    if (!isString(description))
      throw new Error(`templates/${entry.name}/package.json needs a description: it is the listing`);
    found.set(entry.name, { description, files });
  }
  return found;
}

export function render(templates: Map<string, EmbeddedTemplate>): string {
  const plain = Object.fromEntries(
    [...templates].map(([name, { description, files }]) => [name, { description, files: Object.fromEntries(files) }]),
  );
  return `// Generated by scripts/embed-templates.ts from templates/. Do not edit: run \`bun run templates:embed\`.
// The starter templates \`sproutboat init --template\` writes, as text, so the compiled executable carries them.
export const EMBEDDED_TEMPLATES: Record<string, { description: string; files: Record<string, string> }> = ${JSON.stringify(plain, null, 2)};
`;
}

if (import.meta.main) {
  const next = render(readTemplates());
  if (process.argv.includes("--check")) {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : "";
    if (current !== next) {
      console.error("src/templates-embedded.ts is out of date. Run `bun run templates:embed`.");
      process.exit(1);
    }
    console.log("src/templates-embedded.ts is up to date.");
  } else {
    await Bun.write(OUTPUT, next);
    console.log(`wrote src/templates-embedded.ts (${(next.length / 1024).toFixed(0)} KiB)`);
  }
}
